<#
  Starts the local web viewer for Tapo (or any RTSP) cameras.

  - reads cameras.txt (created from cameras.example.txt on the first run)
  - downloads go2rtc (open source RTSP -> browser gateway) on the first run
  - writes go2rtc.yaml and www\cameras.json (both git-ignored; the first holds the passwords)
  - runs go2rtc, which also serves the web page from the www folder

  Stop it with Ctrl+C or by closing the window.

  -Config        use another camera list than cameras.txt
  -GenerateOnly  only write the generated files, do not start anything
#>
param(
    [string]$Config = (Join-Path $PSScriptRoot 'cameras.txt'),
    [switch]$GenerateOnly
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$bin = Join-Path $root 'bin'
$exe = Join-Path $bin 'go2rtc.exe'
$yamlPath = Join-Path $root 'go2rtc.yaml'
$jsonPath = Join-Path $root 'www\cameras.json'
$noBom = New-Object System.Text.UTF8Encoding($false)

function Quote-Yaml([string]$s) { "'" + $s.Replace("'", "''") + "'" }

# ---------------------------------------------------------------- camera list

if (-not (Test-Path $Config)) {
    $example = Join-Path $root 'cameras.example.txt'
    if ($Config -eq (Join-Path $root 'cameras.txt') -and (Test-Path $example)) {
        Copy-Item $example $Config
        Write-Host "Created $Config"
        Write-Host 'Fill in your cameras, save the file, then run this again.'
        Start-Process notepad.exe $Config
        exit 0
    }
    throw "Camera list not found: $Config"
}

$port = 1984
$loginUser = $null
$loginPassword = $null
$cams = @()

foreach ($raw in Get-Content $Config) {
    $line = $raw.Trim()
    if ($line -eq '' -or $line.StartsWith('#')) { continue }
    $eq = $line.IndexOf('=')
    if ($eq -lt 1) { Write-Warning "Ignoring this line (expected name = value): $line"; continue }
    $key = $line.Substring(0, $eq).Trim()
    $val = $line.Substring($eq + 1).Trim()

    if ($key -ieq 'port') {
        $port = [int]$val
    }
    elseif ($key -ieq 'login') {
        $p = $val -split ',', 2
        if ($p.Count -ne 2) { throw "login needs 'user, password': $line" }
        $loginUser = $p[0].Trim()
        $loginPassword = $p[1].Trim()
    }
    else {
        $n = $cams.Count + 1
        $id = "cam$n"
        if ($val.Contains('://')) {
            # a complete stream URL (any RTSP camera, or an http MJPEG stream)
            $cams += [pscustomobject]@{ Id = $id; Name = $key; Hd = $val; Sd = $null }
        }
        else {
            # Tapo: name = camera IP, camera account user, camera account password
            $p = $val -split ',', 3
            if ($p.Count -ne 3) { throw "Camera '$key' needs 'IP, user, password': $line" }
            $hostPart = $p[0].Trim()
            if (-not $hostPart.Contains(':')) { $hostPart = $hostPart + ':554' }
            $auth = [Uri]::EscapeDataString($p[1].Trim()) + ':' + [Uri]::EscapeDataString($p[2].Trim())
            $cams += [pscustomobject]@{
                Id   = $id
                Name = $key
                Hd   = "rtsp://$auth@$hostPart/stream1"
                Sd   = "rtsp://$auth@$hostPart/stream2"
            }
        }
    }
}

if ($cams.Count -eq 0) { throw "No cameras found in $Config" }

# ---------------------------------------------------------------- generated files

$y = New-Object System.Text.StringBuilder
[void]$y.AppendLine('# Generated by start.ps1 - do not edit, do not share (contains camera passwords).')
[void]$y.AppendLine('api:')
[void]$y.AppendLine("  listen: ':$port'")
[void]$y.AppendLine("  static_dir: 'www'")
if ($loginUser) {
    [void]$y.AppendLine('  username: ' + (Quote-Yaml $loginUser))
    [void]$y.AppendLine('  password: ' + (Quote-Yaml $loginPassword))
}
[void]$y.AppendLine('rtsp:')
[void]$y.AppendLine("  listen: ''")
[void]$y.AppendLine('webrtc:')
[void]$y.AppendLine("  listen: ':8555'")
[void]$y.AppendLine('streams:')
$list = @()
foreach ($c in $cams) {
    [void]$y.AppendLine('  ' + $c.Id + ': ' + (Quote-Yaml $c.Hd))
    $sd = $c.Id
    if ($c.Sd) {
        $sd = $c.Id + '-sd'
        [void]$y.AppendLine('  ' + $sd + ': ' + (Quote-Yaml $c.Sd))
    }
    $list += [ordered]@{ id = $c.Id; name = $c.Name; sd = $sd }
}
[IO.File]::WriteAllText($yamlPath, $y.ToString(), $noBom)
[IO.File]::WriteAllText($jsonPath, (ConvertTo-Json -InputObject $list -Compress), $noBom)

Write-Host ("Cameras: " + (($cams | ForEach-Object { $_.Name }) -join ', '))
if ($GenerateOnly) { Write-Host 'Generated go2rtc.yaml and www\cameras.json.'; exit 0 }

# ---------------------------------------------------------------- go2rtc

if (-not (Test-Path $exe)) {
    New-Item -ItemType Directory -Force $bin | Out-Null
    $zip = Join-Path $bin 'go2rtc_win64.zip'
    Write-Host 'Downloading go2rtc (open source, https://github.com/AlexxIT/go2rtc) ...'
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    $ProgressPreference = 'SilentlyContinue'
    Invoke-WebRequest 'https://github.com/AlexxIT/go2rtc/releases/latest/download/go2rtc_win64.zip' -OutFile $zip -UseBasicParsing
    Expand-Archive -Force $zip $bin
    Remove-Item $zip
}

$ips = [Net.Dns]::GetHostAddresses([Net.Dns]::GetHostName()) |
    Where-Object { $_.AddressFamily -eq 'InterNetwork' -and $_.ToString() -match '^(192\.168\.|10\.|172\.(1[6-9]|2\d|3[01])\.)' }

Write-Host ''
Write-Host 'Open the viewer in a browser:'
Write-Host "  this PC:        http://localhost:$port/"
foreach ($ip in $ips) { Write-Host "  other devices:  http://${ip}:$port/" }
if (-not $loginUser) {
    Write-Host 'Anyone on your network can open it. Add a "login = user, password" line to the camera list to protect it.'
}
Write-Host 'If Windows asks about the firewall, allow it on Private networks. Press Ctrl+C to stop.'
Write-Host ''

Push-Location $root
try { & $exe -config $yamlPath } finally { Pop-Location }
